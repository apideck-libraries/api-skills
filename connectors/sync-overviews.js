#!/usr/bin/env node

/**
 * Connector overview sync
 *
 * Pulls each connector's `overview` object from Apideck's connector metadata
 * API (GET /connector/connectors/{id} → data.overview) and writes the result
 * to connectors/overviews.json. That snapshot is the ONLY input generate.js
 * uses to render the "At a glance" section of connector skills — never edit
 * overviews.json (or the generated sections) by hand. Unify's authored
 * overview content (src/specs/{service}/docs/overview.json, served verbatim
 * by the API) stays the single source of truth; re-run this script to pick up
 * new or updated overviews.
 *
 * Not every connector has an overview yet — coverage grows connector by
 * connector on the Apideck side. Connectors without one are simply absent
 * from the snapshot and their skills render unchanged.
 *
 * The snapshot stores each overview object verbatim (minus $schema), even
 * fields generate.js doesn't render yet (supported_resource_categories,
 * responsibility_matrix, external_guides, environment_notes) — deliberate,
 * so the snapshot stays diffable 1:1 against the API and future rendering
 * needs no sync change.
 *
 * Usage:
 *   APIDECK_API_KEY=... APIDECK_APP_ID=... node connectors/sync-overviews.js
 *
 *   # Maintainers with a local unify checkout can sync from the authored
 *   # files directly (identical content — the API serves them verbatim,
 *   # minus the authoring-time $schema key):
 *   node connectors/sync-overviews.js --from-spec-dir=/path/to/unify
 */

const fs = require("fs");
const path = require("path");

const CONNECTORS_DIR = __dirname;
const MANIFEST_PATH = path.join(CONNECTORS_DIR, "manifest.json");
const OUTPUT_PATH = path.join(CONNECTORS_DIR, "overviews.json");
const API_BASE = process.env.APIDECK_API_BASE || "https://unify.apideck.com";

const args = process.argv.slice(2);
const specDirArg = args.find((a) => a.startsWith("--from-spec-dir="));
const specDir = specDirArg ? specDirArg.split("=")[1] : null;

const manifest = JSON.parse(fs.readFileSync(MANIFEST_PATH, "utf-8"));

// Drop authoring-time noise so both sync modes produce identical output.
// $schema is an editor aid in unify's authored files; the API already strips it.
function clean(overview) {
  const { $schema, ...rest } = overview;
  return rest;
}

async function fromApi() {
  const apiKey = process.env.APIDECK_API_KEY;
  const appId = process.env.APIDECK_APP_ID;
  if (!apiKey || !appId) {
    console.error(
      "APIDECK_API_KEY and APIDECK_APP_ID are required (or use --from-spec-dir=/path/to/unify)."
    );
    process.exit(1);
  }

  const overviews = {};
  const failures = [];
  for (const connector of manifest.connectors) {
    const url = `${API_BASE}/connector/connectors/${connector.serviceId}`;
    let res;
    try {
      res = await fetch(url, {
        headers: {
          Authorization: `Bearer ${apiKey}`,
          "x-apideck-app-id": appId,
        },
      });
    } catch (err) {
      failures.push(`${connector.serviceId}: ${err.message}`);
      console.error(`  !! ${connector.serviceId}: ${err.message}`);
      continue;
    }
    if (res.status === 404) {
      console.log(`  -- ${connector.serviceId} (not found)`);
      continue;
    }
    if (!res.ok) {
      failures.push(`${connector.serviceId}: HTTP ${res.status}`);
      console.error(`  !! ${connector.serviceId}: HTTP ${res.status}`);
      continue;
    }
    const body = await res.json();
    const overview = body && body.data && body.data.overview;
    if (overview) {
      overviews[connector.serviceId] = clean(overview);
      console.log(`  OK ${connector.serviceId}`);
    }
  }

  // A partial sync must never overwrite the previous good snapshot — a
  // dropped entry would silently strip that connector's "At a glance"
  // section on the next generate. Fail without writing instead.
  if (failures.length) {
    console.error(
      `\n${failures.length} request(s) failed — snapshot NOT written. Fix and re-run:\n  ${failures.join("\n  ")}`
    );
    process.exit(1);
  }

  return overviews;
}

function fromSpecDir() {
  const overviews = {};
  for (const connector of manifest.connectors) {
    const overviewPath = path.join(
      specDir,
      "src",
      "specs",
      connector.serviceId,
      "docs",
      "overview.json"
    );
    if (!fs.existsSync(overviewPath)) continue;
    overviews[connector.serviceId] = clean(
      JSON.parse(fs.readFileSync(overviewPath, "utf-8"))
    );
    console.log(`  OK ${connector.serviceId}`);
  }
  return overviews;
}

async function main() {
  console.log(
    specDir
      ? `Syncing overviews from spec dir ${specDir}...\n`
      : `Syncing overviews from ${API_BASE}/connector/connectors/{id}...\n`
  );

  const overviews = specDir ? fromSpecDir() : await fromApi();
  const slugs = Object.keys(overviews).sort();

  const snapshot = {
    $comment:
      "GENERATED by connectors/sync-overviews.js — do not edit by hand. Source of truth is Apideck's connector metadata API (GET /connector/connectors/{id} → overview). Re-run the sync to refresh.",
    source: `${API_BASE}/connector/connectors/{id}`,
    overviews: Object.fromEntries(slugs.map((s) => [s, overviews[s]])),
  };

  fs.writeFileSync(OUTPUT_PATH, JSON.stringify(snapshot, null, 2) + "\n");
  console.log(`\nWrote ${slugs.length} overview(s) to connectors/overviews.json.\n`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
